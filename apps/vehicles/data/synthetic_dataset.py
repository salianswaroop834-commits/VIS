def get_all_vehicles():
    """Flattens and returns all 38 vehicles with owner metadata attached."""
    all_v = []
    for u in SYNTHETIC_USERS:
        for v in u["vehicles"]:
            item = dict(v)
            item["owner_name"] = f"{u['first_name']} {u['last_name']}"
            item["owner_phone"] = u["phone_number"]
            item["owner_pan"] = u["pan_number"]
            item["owner_email"] = u["email"]
            item["customer_code"] = u["id_code"]
            all_v.append(item)
    return all_v


def get_vehicle_by_registration(registration_number: str):
    clean = "".join(c for c in registration_number.upper() if c.isalnum())
    for v in get_all_vehicles():
        if "".join(c for c in v["registration_number"].upper() if c.isalnum()) == clean:
            return v
    return None


